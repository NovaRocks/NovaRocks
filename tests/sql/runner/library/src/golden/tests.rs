// Expected spellings come from the frozen spec and Trino 483's metadata
// vocabulary. The floating point oracle in java_float.rs is generated by JDK.
use super::{
    Block, GoldenFile, Section, parse_cell, parse_text, parse_type, render_cell, render_text,
};
use novarocks_test_trino_client::{TrinoValue as V, TypeArgument};

fn check(ty: &str, value: V, expected: &str) {
    let signature = parse_type(ty).unwrap();
    assert_eq!(
        render_cell(&signature, &value).unwrap(),
        expected,
        "type {ty}"
    );
    assert_eq!(
        parse_cell(&signature, expected).unwrap(),
        value,
        "type {ty}"
    );
    assert_eq!(render_cell(&signature, &V::Null).unwrap(), "NULL");
    assert_eq!(parse_cell(&signature, "NULL").unwrap(), V::Null);
}

#[test]
fn scalar_cells_have_typed_inverses_and_explicit_nulls() {
    check("boolean", V::Boolean(true), "true");
    for (ty, value) in [
        ("tinyint", -128),
        ("smallint", 32767),
        ("integer", -2147483648),
        ("bigint", i64::MAX),
    ] {
        check(ty, V::Integer(value), &value.to_string());
    }
    check("real", V::Real(2.0), "2.0");
    check("double", V::Double(0.5), "0.5");
    check("double", V::Double(-0.0), "-0.0");
    for (ty, text, expected) in [
        ("varchar", "hello", "hello"),
        ("char(4)", "x   ", r#""x   ""#),
        ("decimal(38, 2)", "123.00", "123.00"),
        ("date", "-0001-11-30", "-0001-11-30"),
        ("time(6)", "12:01:02.000003", "12:01:02.000003"),
        (
            "time(3) with time zone",
            "12:01:02.000 +08:00",
            "12:01:02.000 +08:00",
        ),
        (
            "timestamp(6)",
            "2024-01-01 00:00:00.000000",
            "2024-01-01 00:00:00.000000",
        ),
        (
            "timestamp(9) with time zone",
            "2024-01-01 00:00:00.000000001 UTC",
            "2024-01-01 00:00:00.000000001 UTC",
        ),
        ("json", r#"{"k": 2}"#, r#"{"k": 2}"#),
    ] {
        check(ty, V::Text(text.to_string()), expected);
    }
    check("varbinary", V::Binary(vec![0, 255, 128]), "AP+A");
    check("varbinary", V::Binary(vec![]), r#""""#);
    check(
        "variant",
        V::Variant(r#"{"b":2,"a":1}"#.into()),
        r#"{"b":2,"a":1}"#,
    );
    let unknown = parse_type("unknown").unwrap();
    assert_eq!(render_cell(&unknown, &V::Null).unwrap(), "NULL");
    assert!(parse_cell(&unknown, "1").is_err());
    assert!(render_cell(&parse_type("tinyint").unwrap(), &V::Integer(128)).is_err());
}

#[test]
fn bare_strings_and_canonical_escapes_preserve_content_and_framing() {
    let samples = [
        ("", r#""""#),
        (" ", r#"" ""#),
        ("NULL", r#""NULL""#),
        ("\"abc", r#""\"abc""#),
        ("-- query 2", r#""-- query 2""#),
        ("a\\b", r#""a\\b""#),
        ("a\tb", r#""a\tb""#),
        ("a\nb", r#""a\nb""#),
        ("a\rb", r#""a\rb""#),
        ("\u{8}\u{c}", r#""\b\f""#),
        ("\u{1a}\u{7f}", r#""\u001A\u007F""#),
        ("尾 ", r#""尾 ""#),
        ("非ASCII/中文", "非ASCII/中文"),
        (" leading", " leading"),
        ("a\"b", "a\"b"),
        ("-value", "-value"),
    ];
    for (text, expected) in samples {
        assert_eq!(render_text(text), expected);
        assert_eq!(parse_text(expected).unwrap(), text);
        check("varchar", V::Text(text.into()), expected);
    }
    for noncanonical in [
        r#""ordinary""#,
        r#""\u001a""#,
        r#""\u007f""#,
        r#""\/""#,
        "tail ",
    ] {
        assert!(parse_text(noncanonical).is_err(), "{noncanonical:?}");
    }
}

#[test]
fn nested_values_use_json_and_maps_sort_wire_key_text() {
    let ty = parse_type("map(integer, varchar)").unwrap();
    let original = V::Map(vec![
        (V::Integer(2), V::Text("y".into())),
        (V::Integer(10), V::Text("ten".into())),
        (V::Integer(1), V::Text("x".into())),
    ]);
    let expected = r#"{"1":"x","10":"ten","2":"y"}"#;
    assert_eq!(render_cell(&ty, &original).unwrap(), expected);
    let parsed = parse_cell(&ty, expected).unwrap();
    let V::Map(entries) = parsed else {
        panic!("map expected");
    };
    assert_eq!(
        entries.iter().map(|(key, _)| key).collect::<Vec<_>>(),
        vec![&V::Integer(1), &V::Integer(10), &V::Integer(2)]
    );
    assert!(parse_cell(&ty, r#"{"2":"y","1":"x"}"#).is_err());
    check(
        "array(boolean)",
        V::Array(vec![V::Boolean(true), V::Null, V::Boolean(false)]),
        "[true,null,false]",
    );
    check(
        "array(decimal(5, 2))",
        V::Array(vec![V::Text("1.00".into())]),
        r#"["1.00"]"#,
    );
    check(
        r#"row(a integer, "select" json)"#,
        V::Row(vec![V::Integer(1), V::Text(r#"{"k": 2}"#.into())]),
        r#"[1,"{\"k\": 2}"]"#,
    );
    check(
        "array(varchar)",
        V::Array(vec![V::Text("中文\u{7f}".into())]),
        r#"["中文\u007F"]"#,
    );
    let ty = parse_type("map(varchar, integer)").unwrap();
    let duplicate = V::Map(vec![
        (V::Text("x".into()), V::Integer(1)),
        (V::Text("x".into()), V::Integer(2)),
    ]);
    assert!(render_cell(&ty, &duplicate).is_err());
}

#[test]
fn nonfinite_and_signed_zero_preserve_floating_point_meaning() {
    for (ty, text) in [
        ("real", "NaN"),
        ("double", "NaN"),
        ("real", "Infinity"),
        ("double", "-Infinity"),
    ] {
        let signature = parse_type(ty).unwrap();
        let value = parse_cell(&signature, text).unwrap();
        assert_eq!(render_cell(&signature, &value).unwrap(), text);
    }
    let signature = parse_type("double").unwrap();
    let V::Double(value) = parse_cell(&signature, "-0.0").unwrap() else {
        panic!("double expected");
    };
    assert_eq!(value.to_bits(), (-0.0f64).to_bits());
    let signature = parse_type("array(double)").unwrap();
    let value = V::Array(vec![V::Double(f64::NAN), V::Double(f64::INFINITY), V::Null]);
    assert_eq!(
        render_cell(&signature, &value).unwrap(),
        r#"["NaN","Infinity",null]"#
    );
    assert!(parse_cell(&parse_type("double").unwrap(), "2").is_err());
}

#[test]
fn type_parser_covers_trino_483_column_vocabulary() {
    // These are columns.rs's type_info/write_type_name variants. The test
    // consumes the metadata contract, not product implementation/source tokens.
    for ty in [
        "unknown",
        "boolean",
        "tinyint",
        "smallint",
        "integer",
        "bigint",
        "real",
        "double",
        "varchar",
        "char(4)",
        "varbinary",
        "date",
        "json",
        "variant",
        "decimal(38, 18)",
    ] {
        parse_type(ty).unwrap();
    }
    for precision in [0, 3, 6, 9] {
        for ty in [
            format!("time({precision})"),
            format!("timestamp({precision})"),
            format!("timestamp({precision}) with time zone"),
        ] {
            parse_type(&ty).unwrap();
        }
    }
    for ty in [
        "time",
        "timestamp",
        "timestamp with time zone",
        "array(decimal(38, 18))",
        "map(varchar, timestamp(9) with time zone)",
        r#"row(a bigint, "select" array(varchar), "quoted""中" map(integer, varchar))"#,
        "row(bigint, varchar)",
        "row()",
    ] {
        parse_type(ty).unwrap();
    }
    let row = parse_type(r#"row("quoted""中" decimal(10, 2))"#).unwrap();
    let TypeArgument::NamedType(field) = &row.arguments[0] else {
        panic!("named row field expected");
    };
    assert_eq!(field.field_name.as_ref().unwrap().name, "quoted\"中");
    assert_eq!(field.type_signature.raw_type, "decimal");
    assert_eq!(
        parse_type("varchar").unwrap().arguments,
        vec![TypeArgument::Long(2_147_483_647)]
    );
    for invalid in [
        "largeint",
        "decimal(39, 0)",
        "decimal(3, 4)",
        "time(13)",
        "map(integer)",
        "array(integer))",
        "char",
        r#"row("a"integer)"#,
        "integer garbage",
    ] {
        assert!(parse_type(invalid).is_err(), "{invalid}");
    }
}

#[test]
fn file_round_trip_keeps_multiple_blocks_shell_legacy_and_empty_sections() {
    let expected = concat!(
        "-- query 1\n",
        "-- types\tbigint\tvarchar\n",
        "id\tnote\n",
        "1\tNULL\n",
        "2\t\"NULL\"\n",
        "-- types\tboolean\n",
        "\"-- flag\"\n",
        "true\n",
        "-- shell\n",
        "0\n",
        "\"\"\n",
        "hello\n",
        "\"-- query 77\"\n",
        "-- legacy\n",
        "old\n",
        "a\\nb\n",
        "\n",
        "-- query 4\n",
    );
    let file = GoldenFile::parse(expected).unwrap();
    assert_eq!(file.sections.len(), 2);
    assert_eq!(file.sections[0].blocks.len(), 4);
    assert!(file.sections[1].blocks.is_empty());
    let Block::Typed { names, .. } = &file.sections[0].blocks[1] else {
        panic!("typed block");
    };
    assert_eq!(names, &["-- flag".to_string()]);
    let Block::Legacy { rows, .. } = &file.sections[0].blocks[3] else {
        panic!("legacy block");
    };
    assert_eq!(rows, &[vec!["a\\nb".to_string()]]);
    assert_eq!(file.render().unwrap(), expected);
    assert_eq!(GoldenFile::default().render().unwrap(), "");
    assert_eq!(GoldenFile::parse("").unwrap(), GoldenFile::default());
}

#[test]
fn file_parser_rejects_noncanonical_or_ambiguous_structure() {
    for invalid in [
        "x\n1\n",
        "-- query 0\n",
        "-- query 1\n-- unknown\n",
        "-- query 1\n-- types\nname\n",
        "-- query 1\n-- types\tbigint\na\tb\n",
        "-- query 1\n-- types\tbigint\na\n1\t2\n",
        "-- query 2\n\n-- query 1\n",
        "-- query 1\n\n-- query 1\n",
        "-- query 1",
        "-- query 1\n\n",
        "-- query 1\n-- types\tvarchar\na\n\"ordinary\"\n",
        "-- query 1\n-- types\tmap(integer, varchar)\na\n{\"2\":\"y\",\"1\":\"x\"}\n",
        "-- query 1\n-- types\tinteger\na\n01\n",
    ] {
        assert!(GoldenFile::parse(invalid).is_err(), "{invalid:?}");
    }
    let invalid = GoldenFile {
        sections: vec![Section {
            step: 1,
            blocks: vec![Block::Typed {
                types: vec![],
                names: vec![],
                rows: vec![],
            }],
        }],
    };
    assert!(invalid.render().is_err());
}
