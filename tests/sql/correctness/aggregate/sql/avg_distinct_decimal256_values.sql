-- Test Objective: AVG DISTINCT unions real Decimal256 values without narrowing.
-- @order_sensitive=true

-- query 1
SELECT CAST(avg(DISTINCT x) AS VARCHAR) AS wide_distinct_avg FROM (VALUES (CAST('1000000000000000000000000000000000000000000000000.00' AS DECIMAL(60,2))),(CAST('1000000000000000000000000000000000000000000000000.00' AS DECIMAL(60,2))),(CAST('3000000000000000000000000000000000000000000000000.00' AS DECIMAL(60,2))),(CAST('3000000000000000000000000000000000000000000000000.00' AS DECIMAL(60,2))),(CAST('5000000000000000000000000000000000000000000000000.00' AS DECIMAL(60,2)))) AS source(x);

-- query 2
SELECT CAST(avg(DISTINCT positive) AS VARCHAR) AS rounded_positive, CAST(avg(DISTINCT negative) AS VARCHAR) AS rounded_negative
FROM (VALUES
(CAST('0.00000000000000001' AS DECIMAL(50,17)),CAST('-0.00000000000000001' AS DECIMAL(50,17))),
(CAST('0.00000000000000002' AS DECIMAL(50,17)),CAST('-0.00000000000000002' AS DECIMAL(50,17))),
(CAST('0.00000000000000002' AS DECIMAL(50,17)),CAST('-0.00000000000000002' AS DECIMAL(50,17)))
) AS source(positive, negative);

-- query 3
SELECT CAST(avg(DISTINCT x) AS VARCHAR) AS bounded_distinct_avg FROM (VALUES (CAST('9999999999999999999999999999999999999999999999999999999999999999999999999999' AS DECIMAL(76,0))),(CAST('9999999999999999999999999999999999999999999999999999999999999999999999999998' AS DECIMAL(76,0))),(CAST('9999999999999999999999999999999999999999999999999999999999999999999999999997' AS DECIMAL(76,0))),(CAST('9999999999999999999999999999999999999999999999999999999999999999999999999996' AS DECIMAL(76,0))),(CAST('9999999999999999999999999999999999999999999999999999999999999999999999999995' AS DECIMAL(76,0))),(CAST('9999999999999999999999999999999999999999999999999999999999999999999999999994' AS DECIMAL(76,0)))) AS source(x);

-- query 4
SELECT CAST(avg(DISTINCT x) AS VARCHAR) AS null_distinct_avg
FROM (VALUES (CAST(NULL AS DECIMAL(60,2)))) AS source(x);
