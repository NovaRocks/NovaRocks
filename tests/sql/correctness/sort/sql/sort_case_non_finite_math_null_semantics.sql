-- @order_sensitive=true
-- @tags=sort,float,null_semantics,case
-- Test Objective:
-- Verify descending order with NULLS LAST for math results selected by CASE.
-- The row ID breaks ties when multiple expressions produce NaN.
WITH t AS (SELECT 1 AS id, CAST(NULL AS DOUBLE) AS d UNION ALL SELECT 2, (- (DECIMAL '3.5')) UNION ALL SELECT 3, DECIMAL '0.0' UNION ALL SELECT 4, DECIMAL '7.25' UNION ALL SELECT 5, (- (DECIMAL '7.25')) UNION ALL SELECT 6, DECIMAL '1.0' UNION ALL SELECT 7, DECIMAL '3.5' UNION ALL SELECT 8, NULL UNION ALL SELECT 9, DECIMAL '2.2' UNION ALL SELECT 10, (- (DECIMAL '0.0'))) SELECT id, CASE WHEN (id = 1) THEN SQRT((- (DECIMAL '1.0'))) WHEN (id = 2) THEN LN((- (DECIMAL '1.0'))) WHEN (id = 3) THEN LN(DECIMAL '0.0') WHEN (id = 4) THEN ACOS(DECIMAL '2.0') WHEN (id = 5) THEN EXP(1000) ELSE d END AS k FROM t ORDER BY k DESC NULLS LAST, id ASC;
