-- @order_sensitive=true
-- @tags=sort,float,null_semantics
-- Test Objective:
-- Verify ascending order with NULLS FIRST for explicit and computed NaN and infinity.
-- The row ID breaks ties between NaN values from casts and math expressions.
WITH t AS (SELECT 1 AS id, CAST('NaN' AS DOUBLE) AS d UNION ALL SELECT 2, CAST('Infinity' AS DOUBLE) UNION ALL SELECT 3, CAST('-Infinity' AS DOUBLE) UNION ALL SELECT 4, SQRT((- (DECIMAL '1.0'))) UNION ALL SELECT 5, LN((- (DECIMAL '1.0'))) UNION ALL SELECT 6, ACOS(DECIMAL '2.0') UNION ALL SELECT 7, DECIMAL '1.25' UNION ALL SELECT 8, (- (DECIMAL '2.5'))) SELECT id, d FROM t ORDER BY d ASC NULLS FIRST, id ASC;
