/// Punctuation and operators recognized by the foundation lexer.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Symbol {
    Ampersand,
    DoubleAmpersand,
    Bang,
    Backslash,
    Caret,
    Colon,
    ColonEq,
    DoubleColon,
    Comma,
    Dot,
    DoubleDot,
    Eq,
    FatArrow,
    Gt,
    Gte,
    LBrace,
    LBracket,
    LParen,
    Lte,
    Lt,
    ShiftLeft,
    Minus,
    Neq,
    NullSafeEq,
    Percent,
    Pipe,
    DoublePipe,
    Plus,
    Question,
    RBrace,
    RBracket,
    RParen,
    Semicolon,
    Slash,
    Star,
    Tilde,
    Arrow,
    LongArrow,
    ShiftRight,
    QuestionAmpersand,
}

impl Symbol {
    pub const fn sql(self) -> &'static str {
        match self {
            Self::Ampersand => "&",
            Self::DoubleAmpersand => "&&",
            Self::Bang => "!",
            Self::Backslash => "\\",
            Self::Caret => "^",
            Self::Colon => ":",
            Self::ColonEq => ":=",
            Self::DoubleColon => "::",
            Self::Comma => ",",
            Self::Dot => ".",
            Self::DoubleDot => "..",
            Self::Eq => "=",
            Self::FatArrow => "=>",
            Self::Gt => ">",
            Self::Gte => ">=",
            Self::LBrace => "{",
            Self::LBracket => "[",
            Self::LParen => "(",
            Self::Lte => "<=",
            Self::Lt => "<",
            Self::ShiftLeft => "<<",
            Self::Minus => "-",
            Self::Neq => "!=",
            Self::NullSafeEq => "<=>",
            Self::Percent => "%",
            Self::Pipe => "|",
            Self::DoublePipe => "||",
            Self::Plus => "+",
            Self::Question => "?",
            Self::RBrace => "}",
            Self::RBracket => "]",
            Self::RParen => ")",
            Self::Semicolon => ";",
            Self::Slash => "/",
            Self::Star => "*",
            Self::Tilde => "~",
            Self::Arrow => "->",
            Self::LongArrow => "->>",
            Self::ShiftRight => ">>",
            Self::QuestionAmpersand => "?&",
        }
    }
}
