use crate::Span;

/// A source token including trivia, with its exact original byte range.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Span,
}

impl Token {
    pub const fn new(kind: TokenKind, span: Span) -> Self {
        Self { kind, span }
    }
}

/// Grammar-level lexical categories; literal values are decoded by AST construction.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum TokenKind {
    Keyword(Keyword),
    Identifier,
    QuotedIdentifier,
    String,
    UnicodeString,
    DollarString,
    BinaryLiteral,
    Integer,
    Decimal,
    Double,
    Symbol(Symbol),
    Trivia(TriviaKind),
    End,
}

/// Source trivia has no hint or execution semantics.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum TriviaKind {
    Whitespace,
    LineComment,
    BlockComment,
}

