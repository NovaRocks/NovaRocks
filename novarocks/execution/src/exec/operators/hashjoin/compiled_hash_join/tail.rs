//! Independent T sources. Range completion follows the final returned page's
//! transfer; no output is generated by an exit hook or pending-finish watch.

use super::super::{
    CanonicalJoinOutput, JoinPairRow, PagedJoinGather,
    build_finalize::{FinalizedBuild, JoinBuildFrame},
    build_state::build_contract,
    join_completion::{RemainingDemand, funded_vec},
    tail_ranges::{TailClaim, TailLease},
};
use super::frame::CompiledJoinFrame;
use super::*;
use crate::exec::pipeline::shape::{ControlStep, Source, SourceKernel};
use novarocks_functions::KernelEvaluationControl;

// Local scan/gather work segmentation, not a row or output capacity limit.
const RANGE_ROWS: usize = 512;
pub(crate) struct CompiledJoinTailSourceFactory {
    declaration: Arc<CompiledJoinFrame>,
    error: Arc<RuntimeErrorState>,
    name: String,
}
impl CompiledJoinTailSourceFactory {
    pub(crate) fn new(declaration: Arc<CompiledJoinFrame>, error: Arc<RuntimeErrorState>) -> Self {
        Self {
            name: format!("COMPILED_JOIN_TAIL (node={})", declaration.node().index()),
            declaration,
            error,
        }
    }
}
impl OperatorFactory for CompiledJoinTailSourceFactory {
    fn name(&self) -> &str {
        &self.name
    }
    fn is_source(&self) -> bool {
        true
    }
    fn bind_pipeline_dop(&self, dop: i32) -> ExecutionResult<()> {
        if self.declaration.participants.tails == 0
            || usize::try_from(dop).ok() != Some(self.declaration.participants.tails)
        {
            return Err(build_contract(
                "join tail pipeline differs from its installed T",
            ));
        }
        Ok(())
    }
    fn create(&self, dop: i32, driver_id: i32) -> Box<dyn Operator> {
        let invalid = self.bind_pipeline_dop(dop).err().or_else(|| {
            (!usize::try_from(driver_id).is_ok_and(|id| id < self.declaration.participants.tails))
                .then(|| build_contract("join tail source has no installed T slot"))
        });
        Box::new(Source::new(JoinTail {
            name: self.name.clone(),
            declaration: self.declaration.clone(),
            error: self.error.clone(),
            control: RuntimeKernelControl::new(self.error.clone()),
            construction: None,
            tracker: None,
            frame: None,
            prepared: None,
            lease: None,
            position: 0,
            done: false,
            prepare_failure: invalid,
        }))
    }
}
struct TailPreparation {
    schemas: PreparedJoinSchemas,
    gather: PagedJoinGather,
    matched: bool,
}
struct JoinTail {
    name: String,
    declaration: Arc<CompiledJoinFrame>,
    error: Arc<RuntimeErrorState>,
    control: RuntimeKernelControl,
    construction: Option<Arc<dyn InputConstructionFactory>>,
    tracker: Option<Arc<MemTracker>>,
    frame: Option<Arc<JoinBuildFrame>>,
    prepared: Option<TailPreparation>,
    lease: Option<TailLease<FinalizedBuild>>,
    position: usize,
    done: bool,
    prepare_failure: Option<ExecutionFailure>,
}
impl JoinTail {
    fn frame(&self) -> ExecutionResult<&Arc<JoinBuildFrame>> {
        if let Some(first) = &self.prepare_failure {
            return Err(first.clone());
        }
        self.frame
            .as_ref()
            .ok_or_else(|| ConstructionFailure::MissingOwner.into())
    }
    fn fail(&mut self, cause: ExecutionFailure) -> ExecutionFailure {
        let cause = self.control.project_required_failure(cause);
        let cause = self
            .frame
            .as_ref()
            .map_or_else(|| cause.clone(), |frame| frame.fail(cause.clone()));
        if let Some(lease) = self.lease.as_mut() {
            lease.fail(cause.clone());
        }
        self.lease = None;
        cause
    }
    fn exit(&mut self) -> ExecutionResult<()> {
        if let Some(cause) = self.error.error() {
            self.fail(cause);
            return Ok(());
        }
        if let Some(lease) = self.lease.as_mut() {
            if lease.check()? == RemainingDemand::Released {
                lease.withdraw_after_demand_released()?;
            } else {
                return Err(self.fail(build_contract(
                    "join tail exited before its pending range transferred",
                )));
            }
        }
        self.lease = None;
        Ok(())
    }
    fn wait(
        &self,
        observable: Arc<crate::runtime::observable::Observable>,
        generation: u64,
    ) -> StepResult {
        let next = if observable.generation() != generation {
            NextStep::Runnable
        } else {
            NextStep::Wait(WaitFact {
                reason: WaitReason::Dependency,
                observable,
                observed_generation: generation,
                deadline: None,
            })
        };
        StepResult::new(None, next, 0)
    }
}
impl OperatorLifecycle for JoinTail {
    fn name(&self) -> &str {
        &self.name
    }
    fn creates_typed_storage(&self) -> bool {
        true
    }
    fn set_construction_factory(&mut self, factory: Arc<dyn InputConstructionFactory>) {
        self.control.bind_construction_factory(factory.clone());
        self.construction = Some(factory);
    }
    fn set_mem_tracker(&mut self, tracker: Arc<MemTracker>) {
        self.control.bind_mem_tracker(tracker.clone());
        self.tracker = Some(tracker);
    }
    fn bind_runtime_state(&mut self, state: &RuntimeState) -> ExecutionResult<()> {
        self.control.bind_runtime_memory(state);
        Ok(())
    }
    fn prepare(&mut self) -> ExecutionResult<()> {
        if let Some(first) = &self.prepare_failure {
            return Err(first.clone());
        }
        if self.prepared.is_some() {
            return Ok(());
        }
        let result = (|| -> ExecutionResult<()> {
            let node = &self.declaration.program.graph().nodes()[self.declaration.node().index()];
            let matched = match node.kind() {
                ProgramNodeKind::Join {
                    join_type: novarocks_local_program::JoinType::RightSemi,
                    ..
                } => true,
                ProgramNodeKind::Join {
                    join_type:
                        novarocks_local_program::JoinType::RightOuter
                        | novarocks_local_program::JoinType::RightAnti
                        | novarocks_local_program::JoinType::FullOuter,
                    ..
                }
                | ProgramNodeKind::NestedLoopJoin {
                    join_type:
                        novarocks_local_program::NestedLoopJoinType::RightOuter
                        | novarocks_local_program::NestedLoopJoinType::FullOuter,
                    ..
                } => false,
                _ => {
                    return Err(build_contract(
                        "join tail has no original build-output role",
                    ));
                }
            };
            let factory = self
                .construction
                .as_ref()
                .ok_or(ConstructionFailure::MissingOwner)?;
            let probe = factory.create_compiled_chunk_schema(self.declaration.probe_layout()?)?;
            let schemas = prepare_join_schemas(
                factory.as_ref(),
                self.declaration.build_layout(),
                self.declaration.scope_layout()?,
                self.declaration.output_layout(),
            )?;
            let owner = self.control.construction_owner(&schemas.output)?;
            let side = match node.kind() {
                ProgramNodeKind::Join {
                    join_type:
                        novarocks_local_program::JoinType::RightSemi
                        | novarocks_local_program::JoinType::RightAnti,
                    ..
                } => CanonicalJoinOutput::Build,
                _ => CanonicalJoinOutput::Pairs,
            };
            let gather = PagedJoinGather::new_canonical(
                schemas.output.clone(),
                &probe,
                &schemas.build,
                side,
                owner.as_ref(),
            )
            .map_err(JoinGatherError::into_execution)?;
            let work = BulkWork {
                owner: owner.as_ref(),
                allocator: AggregateAllocator::new(
                    self.tracker
                        .clone()
                        .ok_or(ConstructionFailure::MissingOwner)?,
                ),
                host: self
                    .control
                    .allocator()
                    .ok_or(ConstructionFailure::MissingOwner)?,
                control: &self.control,
            };
            self.frame = Some(self.declaration.prepare(&work)?);
            self.prepared = Some(TailPreparation {
                schemas,
                gather,
                matched,
            });
            Ok(())
        })();
        if let Err(cause) = &result {
            self.prepare_failure = Some(cause.clone());
        }
        result
    }
    fn activate(&mut self, _: &RuntimeState) -> ExecutionResult<()> {
        let prep = self
            .prepared
            .as_ref()
            .ok_or(ConstructionFailure::MissingOwner)?;
        let owner = self.control.construction_owner(&prep.schemas.output)?;
        let work = BulkWork {
            owner: owner.as_ref(),
            allocator: AggregateAllocator::new(
                self.tracker
                    .clone()
                    .ok_or(ConstructionFailure::MissingOwner)?,
            ),
            host: self
                .control
                .allocator()
                .ok_or(ConstructionFailure::MissingOwner)?,
            control: &self.control,
        };
        self.frame()?.activate(&work)
    }
    fn begin_exit(&mut self) -> ExecutionResult<()> {
        self.exit()
    }
    fn close(&mut self) -> ExecutionResult<()> {
        self.exit()
    }
    fn cancel(&mut self) {
        if let Err(cause) = self.exit() {
            self.error.report_cleanup(&cause);
        }
    }
    fn on_driver_failure(&mut self) {
        self.cancel();
    }
}
impl SourceKernel for JoinTail {
    fn control_observable(&self) -> Option<Arc<crate::runtime::observable::Observable>> {
        self.frame
            .as_ref()
            .map(|frame| frame.completion.observable())
    }
    fn poll_control(&mut self, _: &mut StepContext<'_>) -> ExecutionResult<ControlStep> {
        if let Some(cause) = self.error.error() {
            return Err(self.fail(cause));
        }
        let frame = self.frame()?;
        frame.completion.check()?;
        if frame.completion.remaining_demand()? == RemainingDemand::Released {
            Ok(ControlStep::Runnable)
        } else {
            Ok(ControlStep::Active)
        }
    }
    fn poll_output(&mut self, ctx: &mut StepContext<'_>) -> ExecutionResult<StepResult> {
        let result = (|| -> ExecutionResult<StepResult> {
            if self.done {
                return Ok(StepResult::new(None, NextStep::Finished, 0));
            }
            let frame = self.frame()?.clone();
            let observable = frame.completion.observable();
            let generation = observable.generation();
            frame.completion.check()?;
            if frame.completion.remaining_demand()? == RemainingDemand::Released {
                if let Some(lease) = self.lease.as_mut() {
                    lease.withdraw_after_demand_released()?;
                }
                self.lease = None;
                self.done = true;
                return Ok(StepResult::new(None, NextStep::Finished, 0));
            }
            if self
                .lease
                .as_ref()
                .is_some_and(|lease| self.position == lease.rows().end)
            {
                // Re-entry proves the last returned page transferred. Completing
                // in its producing call could expose EOS before that page.
                self.lease
                    .as_mut()
                    .expect("original pending range")
                    .complete_after_output()?;
                self.lease = None;
            }
            if frame.completion.published()?.is_none() {
                return Ok(self.wait(observable, generation));
            }
            let prep = self
                .prepared
                .as_ref()
                .ok_or(ConstructionFailure::MissingOwner)?;
            let owner = self.control.construction_owner(&prep.schemas.output)?;
            let work = BulkWork {
                owner: owner.as_ref(),
                allocator: AggregateAllocator::new(
                    self.tracker
                        .clone()
                        .ok_or(ConstructionFailure::MissingOwner)?,
                ),
                host: self
                    .control
                    .allocator()
                    .ok_or(ConstructionFailure::MissingOwner)?,
                control: &self.control,
            };
            let ranges = frame.tails(
                NonZeroUsize::new(RANGE_ROWS).expect("nonzero working range"),
                &work,
            )?;
            if self.lease.is_none() {
                match ranges.claim()? {
                    TailClaim::Pending => return Ok(self.wait(observable, generation)),
                    TailClaim::Unavailable => {
                        return Err(build_contract(
                            "join tail retains demand without complete normal Q contributions",
                        ));
                    }
                    TailClaim::Withdrawn => {
                        self.done = true;
                        return Ok(StepResult::new(None, NextStep::Finished, 0));
                    }
                    TailClaim::Finished => {
                        self.done = true;
                        return Ok(StepResult::new(None, NextStep::Finished, 0));
                    }
                    TailClaim::Range(lease) => {
                        self.position = lease.rows().start;
                        self.lease = Some(lease);
                    }
                }
            }
            let lease = self.lease.as_ref().expect("claimed original range");
            let data = lease.artifact();
            let bits = data.matches.as_ref().ok_or_else(|| {
                build_contract("tail publication has no original fixed match bitmap")
            })?;
            let mut pairs = funded_vec(
                owner.as_ref(),
                RANGE_ROWS.min(ctx.work().remaining() as usize),
            )?;
            while self.position < lease.rows().end {
                self.control.checkpoint(0)?;
                if !ctx.work().try_consume(1) {
                    break;
                }
                let row = self.position;
                self.position += 1;
                if bits.is_marked(row)? == prep.matched {
                    pairs.push(JoinPairRow {
                        probe: None,
                        build: Some(data.rows.row(row)?),
                    });
                }
            }
            let output = if pairs.is_empty() {
                None
            } else {
                Some(
                    prep.gather
                        .gather(
                            None,
                            &data.rows,
                            &pairs,
                            owner.as_ref(),
                            &work.host,
                            &self.control,
                        )
                        .map_err(JoinGatherError::into_execution)?
                        .into_chunk(owner.as_ref())
                        .map_err(JoinGatherError::into_execution)?,
                )
            };
            let next = if ctx.work().remaining() == 0
                && output.is_none()
                && self.position < lease.rows().end
            {
                NextStep::Yield
            } else {
                NextStep::Runnable
            };
            Ok(StepResult::new(output, next, 0))
        })();
        result.map_err(|cause| {
            let cause = self.fail(cause);
            ctx.report_failure(cause.clone());
            cause
        })
    }
}
